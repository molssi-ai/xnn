#!/usr/bin/env python
"""Regenerate ``xnn/ffnn/models/amoeba_ladders.py``: the derivative ladders of the HIPPO radial
kernels as Triton device functions.

The eager model evaluates every ladder ``D_n = (1/R d/dR)^n g`` of its exponential-polynomial
kernels through :class:`xnn.ffnn.models.amoeba._LadderPlan`, a fixed linear map from the kernel's
coefficients (and powers of the two exponents) to the coefficients of ``R^p exp(-(n zeta_i + m
zeta_k) R / 2)``, and the series of nearly equal exponents through a recurrence on the series'
coefficients. The fused kernels want the same numbers as straight-line arithmetic on one pair's
registers. This script takes the plans and the series tables of the eager module and writes them
out as code, so the kernels carry no matrices and the two implementations agree by construction.

    python tools/generate_amoeba_ladders.py [--out src/xnn/ffnn/models/amoeba_ladders.py]
"""
import argparse
import math
import re
from pathlib import Path

import numpy as np

from xnn.ffnn.models import amoeba as am

HEADER = '''"""Derivative ladders of the HIPPO radial kernels as Triton device functions.

Generated by ``tools/generate_amoeba_ladders.py`` from the kernel layouts and ladder plans of
:mod:`xnn.ffnn.models.amoeba` (do not edit by hand; regenerate). Each function takes the pair
distance ``R``, its inverse ``inv`` and the exponents of the two atoms, all as Triton tensors of
one block of pairs, and returns ``D_0 .. D_order`` with ``D_n = (1/R d/dR)^n g``. The one-center
and the two-center overlap Coulomb kernels are returned as deficits ``C_n - D_n`` with ``C_n`` the
ladder of ``1/R``: the exponential parts of the damping alone, so that the pair kernels contract
the total charges with the Coulomb (or Ewald) ladder and subtract these small terms instead of
cancelling core-sized terms in the working precision. The squared Slater overlap is returned as
itself. The closed forms of the two-center kernels cancel at nearly equal exponents, where the
series in the exponent difference take over (``*_series``); the ``*_pair`` functions evaluate both
with a stand-in exponent on the pairs of the other form and select per pair, as the compiled path
of the eager module does.
"""
# ruff: noqa: E501
import triton
import triton.language as tl
from triton.language.extra import libdevice
'''


CONSTANTS: list = []


def fnum(x: float) -> str:
    """A float literal that reads back exactly."""
    r = repr(float(x))
    return r if ("." in r or "e" in r or "inf" in r or "nan" in r) else r + ".0"


def fconst(x: float) -> str:
    """A constant for a device function: a literal when it is exact in float32 (Triton compiles
    float literals as float32), otherwise an entry of the float64 table ``CONSTANTS`` loaded
    through ``c_ptr``."""
    x = float(x)
    if float(np.float32(x)) == x:
        return fnum(x)
    if x not in CONSTANTS:
        CONSTANTS.append(x)
    return f"k{CONSTANTS.index(x)}"


class Terms:
    """A series ``{(p, n, m): coefficient}`` whose coefficients are sums of weighted products of
    named locals (``{names tuple: weight}``), closed under multiplication."""

    def __init__(self, terms: dict):
        self.terms = terms

    def __mul__(self, other: "Terms") -> "Terms":
        out: dict = {}
        for (p1, n1, m1), c1 in self.terms.items():
            for (p2, n2, m2), c2 in other.terms.items():
                key = (p1 + p2, n1 + n2, m1 + m2)
                target = out.setdefault(key, {})
                for names1, w1 in c1.items():
                    for names2, w2 in c2.items():
                        names = tuple(sorted(names1 + names2))
                        target[names] = target.get(names, 0.0) + w1 * w2
        return Terms(out)

    def deficit(self) -> "Terms":
        """``C - this``: the terms without the bare ``1/R`` part, negated."""
        return Terms({key: {names: -w for names, w in coef.items()}
                      for key, coef in self.terms.items() if key[1:] != (0, 0)})

    @staticmethod
    def code(coef: dict) -> str:
        parts = []
        for names, w in coef.items():
            if w == 0.0:
                continue
            factors = [fnum(w)] + list(names) if (w != 1.0 or not names) else list(names)
            parts.append(" * ".join(factors))
        return " + ".join(parts) if parts else "0.0"


def powers_code(lines: list, var: str, inv: str, lo: int, hi: int, prefix: str) -> dict:
    """Emit ``var^p`` for ``lo <= p <= hi`` as locals ``prefix_p`` (``prefix_m3`` for ``-3``) from
    running products of ``var`` and ``inv``; returns ``{p: local name}``."""
    names = {0: None}
    for p in range(1, hi + 1):
        name = f"{prefix}{p}"
        lines.append(f"    {name} = {var}" if p == 1 else f"    {name} = {names[p - 1]} * {var}")
        names[p] = name
    for p in range(-1, lo - 1, -1):
        name = f"{prefix}m{-p}"
        lines.append(f"    {name} = {inv}" if p == -1 else f"    {name} = {names[p + 1]} * {inv}")
        names[p] = name
    return names


def product(*factors: str) -> str:
    """The product of the given factor names, dropping ``None`` (a unit factor)."""
    parts = [f for f in factors if f]
    return " * ".join(parts) if parts else "1.0"


def emit_closed(name: str, terms: Terms, order: int, setup: list, zi: str = "zi", zk: str = "zk") -> str:
    """A device function of the closed-form ladder of ``terms`` to ``order``."""
    keys = tuple(terms.terms)
    plan = am._LadderPlan(keys, order)
    lines = ["@triton.jit", f"def {name}(c_ptr, R, inv, {zi}, {zk}):"] + [f"    {s}" for s in setup]
    # the kernel's coefficients
    for t, key in enumerate(keys):
        lines.append(f"    c{t} = {Terms.code(terms.terms[key])}")
    # powers of the exponents and of R, the exponentials
    za = powers_code(lines, zi, None, 0, max(plan.feature_a), "zia")
    zb = powers_code(lines, zk, None, 0, max(plan.feature_b), "zkb")
    rp = powers_code(lines, "R", "inv", min(plan.powers), max(plan.powers), "rp")
    ex = {}
    for n, m in plan.exps:
        if (n, m) == (0, 0):
            ex[(n, m)] = None
            continue
        ex[(n, m)] = f"e{n}{m}"
        arg = " + ".join(f"{fnum(0.5 * v)} * {z}" for v, z in ((n, zi), (m, zk)) if v)
        lines.append(f"    e{n}{m} = libdevice.exp(-({arg}) * R)")
    # the features c_t zi^a zk^b
    for j, (t, a, b) in enumerate(zip(plan.feature_t, plan.feature_a, plan.feature_b)):
        lines.append(f"    f{j} = {product(f'c{t}', za[a], zb[b])}")
    # the basis R^p exp(...)
    basis = []
    for j, (bp, be) in enumerate(zip(plan.basis_p, plan.basis_e)):
        p, (n, m) = plan.powers[bp], plan.exps[be]
        lines.append(f"    b{j} = {product(rp[p], ex[(n, m)])}")
        basis.append(f"b{j}")
    outs = []
    for o in range(order + 1):
        parts = []
        for j in range(plan.n_basis):
            coef = [(plan.weights[f][j * (order + 1) + o], f) for f in range(len(plan.feature_t))]
            coef = [(w, f) for w, f in coef if w != 0.0]
            if not coef:
                continue
            inner = " + ".join(f"{fconst(w)} * f{f}" if w != 1.0 else f"f{f}" for w, f in coef)
            parts.append(f"{basis[j]} * ({inner})")
        lines.append(f"    d{o} = {' + '.join(parts) if parts else '0.0 * R'}")
        outs.append(f"d{o}")
    lines.append(f"    return {', '.join(outs)}")
    return "\n".join(lines) + "\n"


def emit_series(name: str, kind: str, order: int, deficit: bool = False) -> str:
    """A device function of the near-equal series ladder (``kind`` "coulomb" or "slater"; the
    Slater one squared, for the repulsion), the recurrence of ``_near_ladder`` unrolled; with
    ``deficit`` the Coulomb kernel's deficit ``C_n - D_n`` (the bare ``1/R`` part dropped, the
    series negated)."""
    powers, W = {"coulomb": (am._COULOMB_POWERS, am._COULOMB_W), "slater": (am._SLATER_POWERS, am._SLATER_W)}[kind]
    squared = kind == "slater"
    lines = ["@triton.jit", f"def {name}(c_ptr, R, inv, zi, zk):",
             "    rho = (zi - zk) / (zi + zk)", "    rho2 = rho * rho"]
    rk = [None]
    for k in range(1, am._NEAR_TERMS + 1):
        lines.append("    rho2_1 = rho2" if k == 1 else f"    rho2_{k} = rho2_{k - 1} * rho2")
        rk.append(f"rho2_{k}")
    scale = "0.5 * (zi + zk)" if kind == "coulomb" else "0.25 * (zi + zk)"
    lines.append(f"    scale = {scale}")
    sp = powers_code(lines, "scale", None, 0, powers[-1], "sc")
    if squared:
        lines.append("    w = tl.maximum(1.0 - rho2, 0.0)")
        lines.append("    w15 = w * tl.sqrt(w)")
    # the series coefficients Q_j of R^(lowest + j)
    q = []
    for n, pw in enumerate(powers):
        inner = " + ".join(f"{fconst(W[n][k])} * {rk[k]}" if k else fconst(W[n][k])
                           for k in range(len(W[n])) if W[n][k] != 0.0)
        if not inner:
            inner = "0.0"
        factor = product(sp[pw], "w15" if squared else None)
        sign = "" if (squared or deficit) else "-"
        lines.append(f"    q0_{n} = {sign}({inner}) * {factor}")
        q.append(f"q0_{n}")
    inverse = 0.0 if (squared or deficit) else 1.0
    lowest = powers[0] if squared else powers[0] - 1
    lam = "scale"
    lines.append("    decay = libdevice.exp(-scale * R)")
    start = (min(lowest, -1) if inverse else lowest) - 2 * order
    hi = lowest + len(q) - 1
    rp = powers_code(lines, "R", "inv", start, hi, "rp")
    low, factor = lowest, 1.0
    values = []
    for level in range(order + 1):
        terms = " + ".join(f"{qj} * {rp[low + j]}" if rp[low + j] else qj for j, qj in enumerate(q))
        extra = f" + {fconst(inverse * factor)} * {rp[-1 - 2 * level]}" if inverse else ""
        lines.append(f"    v{level} = decay * ({terms}){extra}")
        values.append(f"v{level}")
        if level < order:
            nxt = []
            for j in range(len(q) + 1):
                parts = []
                if j < len(q):
                    parts.append(f"{fconst(float(low + j))} * {q[j]}" if low + j != 1 else q[j])
                if j > 0:
                    parts.append(f"- {lam} * {q[j - 1]}")
                expr = " ".join(parts).replace("  ", " ")
                if expr.startswith("- "):
                    expr = "-" + expr[2:]
                lines.append(f"    q{level + 1}_{j} = {expr if expr else '0.0 * R'}")
                nxt.append(f"q{level + 1}_{j}")
            q = nxt
            low -= 2
            factor *= -1.0 - 2.0 * level
    if squared:
        outs = []
        for n in range(order + 1):
            terms = " + ".join(f"{fconst(float(math.comb(n, k)))} * {values[k]} * {values[n - k]}"
                               if math.comb(n, k) != 1 else f"{values[k]} * {values[n - k]}" for k in range(n + 1))
            lines.append(f"    s{n} = {terms}")
            outs.append(f"s{n}")
        values = outs
    lines.append(f"    return {', '.join(values)}")
    return "\n".join(lines) + "\n"


def emit_pair(name: str, closed: str, series: str, order: int, threshold: float) -> str:
    """Both forms on every pair with a stand-in exponent, selected per pair."""
    outs = ", ".join(f"d{o}" for o in range(order + 1))
    souts = ", ".join(f"s{o}" for o in range(order + 1))
    couts = ", ".join(f"c{o}" for o in range(order + 1))
    lines = ["@triton.jit", f"def {name}(c_ptr, R, inv, zi, zk):",
             f"    near = tl.abs(zi - zk) * R < {fnum(threshold)}",
             "    zk_series = tl.where(near, zk, zi)",
             "    zk_closed = tl.where(near, 1.5 * zi + 1.0, zk)",
             f"    {souts} = {series}(c_ptr, R, inv, zi, zk_series)",
             f"    {couts} = {closed}(c_ptr, R, inv, zi, zk_closed)"]
    for o in range(order + 1):
        lines.append(f"    d{o} = tl.where(near, s{o}, c{o})")
    lines.append(f"    return {outs}")
    return "\n".join(lines) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(Path(__file__).resolve().parents[1] / "src/xnn/ffnn/models/amoeba_ladders.py"))
    args = ap.parse_args()
    one = {(): 1.0}

    def named(n: str) -> dict:
        return {(n,): 1.0}

    # the kernels, as the eager module defines them (the coefficient locals in `setup`)
    core_valence = Terms({(-1, 0, 0): one, (-1, 0, 2): {(): -1.0}, (0, 0, 2): {("zk",): -0.5}})
    overlap = Terms({(-1, 0, 0): one, (-1, 2, 0): named("ca"), (0, 2, 0): named("cb"),
                     (-1, 0, 2): named("cc"), (0, 0, 2): named("cd")})
    overlap_setup = ["A = zk * zk / (zk * zk - zi * zi)", "B = zi * zi / (zi * zi - zk * zk)",
                     "ca = -A * A * (1.0 + 2.0 * B)", "cb = -A * A * 0.5 * zi",
                     "cc = -B * B * (1.0 + 2.0 * A)", "cd = -B * B * 0.5 * zk"]
    slater = Terms({(0, 0, 1): named("sa"), (-1, 0, 1): named("sb"), (0, 1, 0): named("sc_"),
                    (-1, 1, 0): named("sd")})
    slater_setup = ["delta = zi * zi - zk * zk", "zz = zi * zk",
                    "pref = 8.0 * zz * tl.sqrt(zz) / (delta * delta * delta)",
                    "sa = pref * zi * delta", "sb = -8.0 * pref * zz", "sc_ = pref * zk * delta",
                    "sd = 8.0 * pref * zz"]
    squared = slater * slater
    chunks = ["# the deficit of the one-center charge-penetration kernel [1 - (1 + zeta R / 2) e^(-zeta R)] / R\n"
              "# of the exponent zk: (1 + zeta R / 2) e^(-zeta R) / R and its ladder, orders 0..4 (pass the\n"
              "# source atom's exponent as zk)\n"
              + emit_closed("core_valence_deficit4", core_valence.deficit(), 4, [], zi="zi", zk="zk"),
              "# the deficit of the two-center overlap Coulomb kernel, closed form and series, orders 0..5 and 0..3\n"
              + emit_closed("overlap_deficit_closed5", overlap.deficit(), 5, overlap_setup),
              emit_series("overlap_deficit_series5", "coulomb", 5, deficit=True),
              emit_pair("overlap_deficit5", "overlap_deficit_closed5", "overlap_deficit_series5", 5, am._NEAR_EQUAL),
              emit_closed("overlap_deficit_closed3", overlap.deficit(), 3, overlap_setup),
              emit_series("overlap_deficit_series3", "coulomb", 3, deficit=True),
              emit_pair("overlap_deficit3", "overlap_deficit_closed3", "overlap_deficit_series3", 3, am._NEAR_EQUAL),
              "# the squared Slater overlap of the Pauli repulsion, closed form and series, orders 0..5\n"
              + emit_closed("squared_overlap_closed5", squared, 5, slater_setup),
              emit_series("squared_overlap_series5", "slater", 5),
              emit_pair("squared_overlap5", "squared_overlap_closed5", "squared_overlap_series5", 5, am._NEAR_EQUAL)]
    body = "\n\n".join(chunks)
    # every function loads the table entries it uses right after its signature
    out = []
    for block in body.split("@triton.jit\n"):
        if not block.startswith("def "):
            out.append(block)
            continue
        head, rest = block.split("\n", 1)
        used = sorted({int(t) for t in re.findall(r"\bk(\d+)\b", rest)})
        loads = "".join(f"    k{j} = tl.load(c_ptr + {j}).to(R.dtype)\n" for j in used)
        out.append(head + "\n" + loads + rest)
    table = ",\n".join("    " + fnum(c) for c in CONSTANTS)
    tail = (f"\n\n#: the float64 constants the device functions load through ``c_ptr`` (the inexact ones in float32)\n"
            f"CONSTANTS = (\n{table},\n)\n")
    Path(args.out).write_text(HEADER + "\n\n" + "@triton.jit\n".join(out) + tail)
    print(args.out, sum(c.count("\n") for c in chunks), "lines")


if __name__ == "__main__":
    main()
