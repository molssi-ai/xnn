@triton.jit
def _switch_t_1000(r, cutoff, width, HAS_SWITCH: tl.constexpr, r_t):
    """Tangent of ``_switch`` along the arguments r."""
    if HAS_SWITCH:
        u = tl.minimum(tl.maximum((cutoff - r) / width, 0.0), 1.0)
        u_t = tl.where(tl.maximum((cutoff - r) / width, 0.0) < 1.0, tl.where((cutoff - r) / width > 0.0, -r_t / width, tl.where(0.0 > (cutoff - r) / width, 0.0, 0.5 * (-r_t / width + 0.0))), tl.where(1.0 < tl.maximum((cutoff - r) / width, 0.0), 0.0, 0.5 * (tl.where((cutoff - r) / width > 0.0, -r_t / width, tl.where(0.0 > (cutoff - r) / width, 0.0, 0.5 * (-r_t / width + 0.0))) + 0.0)))
        sw = u * u * u * (10.0 + u * (6.0 * u - 15.0))
        sw_t = ((u_t * u + u * u_t) * u + u * u * u_t) * (10.0 + u * (6.0 * u - 15.0)) + u * u * u * (u_t * (6.0 * u - 15.0) + u * (6.0 * u_t))
        slope = tl.where((u > 0.0) & (u < 1.0), -30.0 * u * u * (1.0 - u) * (1.0 - u) / width, 0.0)
        slope_t = tl.where((u > 0.0) & (u < 1.0), (((-30.0 * u_t * u + -30.0 * u * u_t) * (1.0 - u) + -30.0 * u * u * -u_t) * (1.0 - u) + -30.0 * u * u * (1.0 - u) * -u_t) / width, 0.0)
    else:
        sw = r * 0.0 + 1.0
        sw_t = sw * 0.0
        slope = r * 0.0
        slope_t = slope * 0.0
    return (sw, slope, sw_t, slope_t)


