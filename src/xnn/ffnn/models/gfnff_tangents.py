@triton.jit
def _quartic_t_100(r, rad, c, r_t):
    """Tangent of ``_quartic`` along the arguments r."""
    y = r / rad
    y_t = r_t / rad
    y2 = y * y
    y2_t = y_t * y + y * y_t
    f = 1.0 / (1.0 + c * y2 * y2)
    f_t = -(1.0 / (1.0 + c * y2 * y2) * (c * y2_t * y2 + c * y2 * y2_t) / (1.0 + c * y2 * y2))
    return (f, -4.0 * c * y2 * y / rad * f * f, f_t, ((-4.0 * c * y2_t * y + -4.0 * c * y2 * y_t) / rad * f + -4.0 * c * y2 * y / rad * f_t) * f + -4.0 * c * y2 * y / rad * f * f_t)


@triton.jit
def _angles_t(x_ptr, idx_ptr, par_ptr, g_ptr, e_ptr, c_ptr, x_ptr_t, g_ptr_t, BLOCK: tl.constexpr):
    """Tangent of the kernel ``_angles``: tangents read and written through ``x_ptr_t``, ``g_ptr_t``."""
    p = tl.program_id(0).to(tl.int64)
    c = tl.load(idx_ptr + 3 * p)
    a = tl.load(idx_ptr + 3 * p + 1)
    b = tl.load(idx_ptr + 3 * p + 2)
    ux, uy, uz, ru, ux_t, uy_t, uz_t, ru_t = _delta_t_200(x_ptr, a, c, x_ptr_t)
    vx, vy, vz, rv, vx_t, vy_t, vz_t, rv_t = _delta_t_200(x_ptr, b, c, x_ptr_t)
    cs = (ux * vx + uy * vy + uz * vz) / (ru * rv)
    cs_t = (ux_t * vx + ux * vx_t + (uy_t * vy + uy * vy_t) + (uz_t * vz + uz * vz_t)) / (ru * rv) - (ux * vx + uy * vy + uz * vz) / (ru * rv) * (ru_t * rv + ru * rv_t) / (ru * rv)
    kk = tl.load(par_ptr + 5 * p + 2)
    cd = tl.load(c_ptr + 1)
    fa, dfa, fa_t, dfa_t = _quartic_t_100(ru, tl.load(par_ptr + 5 * p + 3), cd, ru_t)
    fb, dfb, fb_t, dfb_t = _quartic_t_100(rv, tl.load(par_ptr + 5 * p + 4), cd, rv_t)
    ea = cs - tl.load(par_ptr + 5 * p)
    ea_t = cs_t
    dea = 2.0 * ea
    dea_t = 2.0 * ea_t
    ea_t = ea_t * ea + ea * ea_t
    ea = ea * ea
    if tl.load(par_ptr + 5 * p + 1) > 0.5:
        wx = uy * vz - uz * vy
        wx_t = uy_t * vz + uy * vz_t - (uz_t * vy + uz * vy_t)
        wy = uz * vx - ux * vz
