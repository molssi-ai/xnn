    tl.atomic_add(glog_ptr_t + i, de_t * fp * ci, sem='relaxed')
    tl.atomic_add(glog_ptr + j, de * fp * cj, sem='relaxed')
    tl.atomic_add(glog_ptr_t + j, de_t * fp * cj, sem='relaxed')
