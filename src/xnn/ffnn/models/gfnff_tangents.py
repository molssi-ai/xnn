def _vdelta_t_2000(x_ptr, i, j, m, x_ptr_t):
    """Tangent of ``_vdelta`` along the arguments x_ptr."""
    dx = tl.load(x_ptr + 3 * i, mask=m, other=0.0) - tl.load(x_ptr + 3 * j, mask=m, other=0.0)
    dx_t = tl.load(x_ptr_t + 3 * i, mask=m, other=0.0) - tl.load(x_ptr_t + 3 * j, mask=m, other=0.0)
    dy = tl.load(x_ptr + 3 * i + 1, mask=m, other=0.0) - tl.load(x_ptr + 3 * j + 1, mask=m, other=0.0)
    dy_t = tl.load(x_ptr_t + 3 * i + 1, mask=m, other=0.0) - tl.load(x_ptr_t + 3 * j + 1, mask=m, other=0.0)
    dz = tl.load(x_ptr + 3 * i + 2, mask=m, other=0.0) - tl.load(x_ptr + 3 * j + 2, mask=m, other=0.0)
    dz_t = tl.load(x_ptr_t + 3 * i + 2, mask=m, other=0.0) - tl.load(x_ptr_t + 3 * j + 2, mask=m, other=0.0)
    return (dx, dy, dz, tl.sqrt(dx * dx + dy * dy + dz * dz), dx_t, dy_t, dz_t, 0.5 * (dx_t * dx + dx * dx_t + (dy_t * dy + dy * dy_t) + (dz_t * dz + dz * dz_t)) / tl.sqrt(dx * dx + dy * dy + dz * dz))


