def _atom_terms_t(cnt_ptr, lcn_ptr, dl_ptr, rhs_ptr, dxl_ptr, x0_ptr, kap_ptr, ref_ptr, nref_ptr, al_ptr, sw_ptr, s_ptr, ds_ptr, c_ptr, n, cnt_ptr_t, lcn_ptr_t, dl_ptr_t, rhs_ptr_t, dxl_ptr_t, s_ptr_t, ds_ptr_t, NREF: tl.constexpr, NFREQ: tl.constexpr, BLOCK: tl.constexpr):
    """Tangent of the kernel ``_atom_terms``: tangents read and written through ``cnt_ptr_t``, ``lcn_ptr_t``, ``dl_ptr_t``, ``rhs_ptr_t``, ``dxl_ptr_t``, ``s_ptr_t``, ``ds_ptr_t``."""
    i = tl.program_id(0).to(tl.int64)
    ex = tl.exp(tl.load(c_ptr + 9) - tl.load(cnt_ptr + i))
    ex_t = tl.exp(tl.load(c_ptr + 9) - tl.load(cnt_ptr + i)) * -tl.load(cnt_ptr_t + i)
    lcn = tl.load(c_ptr + 10) - tl.log(1.0 + ex)
    lcn_t = -(ex_t / (1.0 + ex))
    tl.store(lcn_ptr + i, lcn)
    tl.store(lcn_ptr_t + i, lcn_t)
    tl.store(dl_ptr + i, ex / (1.0 + ex))
    tl.store(dl_ptr_t + i, ex_t / (1.0 + ex) - ex / (1.0 + ex) * ex_t / (1.0 + ex))
    kap = tl.load(kap_ptr + i)
    sq = tl.where(lcn > 0.0, tl.sqrt(tl.where(lcn > 0.0, lcn, 1.0)), 0.0)
    sq_t = tl.where(lcn > 0.0, 0.5 * tl.where(lcn > 0.0, lcn_t, 0.0) / tl.sqrt(tl.where(lcn > 0.0, lcn, 1.0)), 0.0)
    tl.store(rhs_ptr + i, tl.load(x0_ptr + i) + kap * sq)
    tl.store(rhs_ptr_t + i, kap * sq_t)
    tl.store(dxl_ptr + i, tl.where(sq > 0.0, 0.5 * kap / sq, 0.0))
    tl.store(dxl_ptr_t + i, tl.where(sq > 0.0, -(0.5 * kap / sq * sq_t / sq), 0.0))
    nr = tl.load(nref_ptr + i)
    norm = lcn * 0.0
    norm_t = norm * 0.0
    dnorm = lcn * 0.0
    dnorm_t = dnorm * 0.0
    for r in tl.static_range(NREF):
        d = lcn - tl.load(ref_ptr + i * NREF + r)
        d_t = lcn_t
        w = tl.where(nr > r, tl.exp(-4.0 * d * d), 0.0)
        w_t = tl.where(nr > r, tl.exp(-4.0 * d * d) * (-4.0 * d_t * d + -4.0 * d * d_t), 0.0)
        norm += w
        norm_t += w_t
        dnorm += -8.0 * d * w
        dnorm_t += -8.0 * d_t * w + -8.0 * d * w_t
    for k in tl.static_range(NFREQ):
        acc = lcn * 0.0
        acc_t = acc * 0.0
        dacc = lcn * 0.0
        dacc_t = dacc * 0.0
        for r in tl.static_range(NREF):
            d = lcn - tl.load(ref_ptr + i * NREF + r)
            d_t = lcn_t
            w = tl.where(nr > r, tl.exp(-4.0 * d * d), 0.0)
            w_t = tl.where(nr > r, tl.exp(-4.0 * d * d) * (-4.0 * d_t * d + -4.0 * d * d_t), 0.0)
            a = tl.load(al_ptr + (k * NREF + r) * n + i)
            acc += w * a
            acc_t += w_t * a
            dacc += -8.0 * d * w * a
            dacc_t += (-8.0 * d_t * w + -8.0 * d * w_t) * a
        alpha = acc / norm
        alpha_t = acc_t / norm - acc / norm * norm_t / norm
        sw = tl.load(sw_ptr + k)
        tl.store(s_ptr + i * NFREQ + k, alpha * sw)
        tl.store(s_ptr_t + i * NFREQ + k, alpha_t * sw)
        tl.store(ds_ptr + i * NFREQ + k, (dacc - alpha * dnorm) / norm * sw)
        tl.store(ds_ptr_t + i * NFREQ + k, ((dacc_t - (alpha_t * dnorm + alpha * dnorm_t)) / norm - (dacc - alpha * dnorm) / norm * norm_t / norm) * sw)


@triton.jit
def _solve_small_t(mat_ptr, rhs_ptr, fac_ptr, sol_ptr, dxl_ptr, glog_ptr, e_ptr, dim, n, mat_ptr_t, rhs_ptr_t, fac_ptr_t, sol_ptr_t, dxl_ptr_t, glog_ptr_t, BLOCK: tl.constexpr):
    """Tangent of the kernel ``_solve_small``: tangents read and written through ``mat_ptr_t``, ``rhs_ptr_t``, ``fac_ptr_t``, ``sol_ptr_t``, ``dxl_ptr_t``, ``glog_ptr_t``."""
    for j in range(0, dim):
        d = tl.load(mat_ptr + j * dim + j)
        d_t = tl.load(mat_ptr_t + j * dim + j)
        for k in range(0, j):
            l = tl.load(fac_ptr + j * dim + k)
            l_t = tl.load(fac_ptr_t + j * dim + k)
            d -= l * l * tl.load(fac_ptr + k * dim + k)
            d_t -= (l_t * l + l * l_t) * tl.load(fac_ptr + k * dim + k) + l * l * tl.load(fac_ptr_t + k * dim + k)
        tl.store(fac_ptr + j * dim + j, d)
        tl.store(fac_ptr_t + j * dim + j, d_t)
        for i in range(j + 1, dim):
            v = tl.load(mat_ptr + i * dim + j)
            v_t = tl.load(mat_ptr_t + i * dim + j)
            for k in range(0, j):
                v -= tl.load(fac_ptr + i * dim + k) * tl.load(fac_ptr + j * dim + k) * tl.load(fac_ptr + k * dim + k)
                v_t -= (tl.load(fac_ptr_t + i * dim + k) * tl.load(fac_ptr + j * dim + k) + tl.load(fac_ptr + i * dim + k) * tl.load(fac_ptr_t + j * dim + k)) * tl.load(fac_ptr + k * dim + k) + tl.load(fac_ptr + i * dim + k) * tl.load(fac_ptr + j * dim + k) * tl.load(fac_ptr_t + k * dim + k)
            tl.store(fac_ptr + i * dim + j, v / d)
            tl.store(fac_ptr_t + i * dim + j, v_t / d - v / d * d_t / d)
    for i in range(0, dim):
        v = tl.load(rhs_ptr + i)
        v_t = tl.load(rhs_ptr_t + i)
        for k in range(0, i):
            v -= tl.load(fac_ptr + i * dim + k) * tl.load(sol_ptr + k)
            v_t -= tl.load(fac_ptr_t + i * dim + k) * tl.load(sol_ptr + k) + tl.load(fac_ptr + i * dim + k) * tl.load(sol_ptr_t + k)
        tl.store(sol_ptr + i, v)
        tl.store(sol_ptr_t + i, v_t)
    for i in range(0, dim):
        tl.store(sol_ptr_t + i, tl.load(sol_ptr_t + i) / tl.load(fac_ptr + i * dim + i) - tl.load(sol_ptr + i) / tl.load(fac_ptr + i * dim + i) * tl.load(fac_ptr_t + i * dim + i) / tl.load(fac_ptr + i * dim + i))
        tl.store(sol_ptr + i, tl.load(sol_ptr + i) / tl.load(fac_ptr + i * dim + i))
    for r in range(0, dim):
        i = dim - 1 - r
        v = tl.load(sol_ptr + i)
        v_t = tl.load(sol_ptr_t + i)
        for k in range(i + 1, dim):
            v -= tl.load(fac_ptr + k * dim + i) * tl.load(sol_ptr + k)
            v_t -= tl.load(fac_ptr_t + k * dim + i) * tl.load(sol_ptr + k) + tl.load(fac_ptr + k * dim + i) * tl.load(sol_ptr_t + k)
        tl.store(sol_ptr + i, v)
        tl.store(sol_ptr_t + i, v_t)
    for i in range(0, n):
        tl.store(glog_ptr + i, tl.load(glog_ptr + i) - tl.load(sol_ptr + i) * tl.load(dxl_ptr + i))
        tl.store(glog_ptr_t + i, tl.load(glog_ptr_t + i) - (tl.load(sol_ptr_t + i) * tl.load(dxl_ptr + i) + tl.load(sol_ptr + i) * tl.load(dxl_ptr_t + i)))
    acc = tl.load(sol_ptr) * 0.0
    acc_t = acc * 0.0
    for k in range(0, dim):
        acc += tl.load(sol_ptr + k) * tl.load(rhs_ptr + k)
        acc_t += tl.load(sol_ptr_t + k) * tl.load(rhs_ptr + k) + tl.load(sol_ptr + k) * tl.load(rhs_ptr_t + k)
    tl.store(e_ptr + 8, -0.5 * acc)


