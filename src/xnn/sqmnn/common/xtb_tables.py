def n_gaussians(method: str, n: int, l: int, second_s: bool = False) -> int:
    """Primitives per shell: GFN1 uses STO-6G (``d`` and 1s: STO-4G, the second hydrogen
    ``s`` shell: STO-3G); GFN2 uses STO-4G (``d`` and 1s: STO-3G, sixth-row ``s`` and
    ``p``: STO-6G); GFN0 uses STO-4G for ``s`` and ``d`` and STO-3G for ``p`` shells (1s:
    STO-3G, the second hydrogen ``s`` shell: STO-2G, sixth-row ``s`` and ``p``: STO-6G)."""
    if method == "gfn0":
        if second_s:
            return 2
        if n == 1:
            return 3
        if l == 2:
            return 4
        return 6 if n == 6 else (3 if l == 1 else 4)
    if method == "gfn1":
        if second_s:
            return 3
        if l == 2:
            return 4
        return 4 if n == 1 else 6
    if l == 2 or n == 1:
        return 3
    return 6 if n == 6 else 4


